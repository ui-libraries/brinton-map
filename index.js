/* Brinton Map: accessible version
 * Depends only on Leaflet 1.9.x (no jQuery, d3, Font Awesome, or Leaflet plugins).
 */
(function () {
  'use strict';

  /* ------------------------------------------------------------------ *
   * Configuration
   * ------------------------------------------------------------------ */
  var DATA_URL = 'data/Brinton.geojson';

  var MARKER_STYLE = {
    radius: 9, // ~18px dot plus border, easier to hit than the old 7px
    fillColor: 'black',
    color: 'orange',
    weight: 2,
    opacity: 1,
    fillOpacity: 1
  };
  var ACTIVE_STYLE = {
    radius: 9,
    fillColor: 'yellow',
    color: '#3978BF',
    weight: 3,
    opacity: 1,
    fillOpacity: 1
  };

  var MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July',
    'August', 'September', 'October', 'November', 'December'];

  // Display order for the range-based filters. Any extra values found in the data are appended.
  var FILTER_GROUPS = [
    { id: 'year', label: 'Year', prop: 'Year', preferred: ['1904', '1905', '1906', '1907', '1908'] },
    { id: 'month', label: 'Month', prop: 'Month', preferred: MONTHS },
    { id: 'day', label: 'Day of month', prop: 'Day', searchable: true },
    { id: 'town', label: 'Town', prop: 'Town', searchable: true },
    { id: 'state', label: 'State or territory', prop: 'State' },
    {
      id: 'amount', label: 'Amount made', prop: 'Amount_Made_ranges',
      preferred: ['$0 - $31.55', '$31.56 - $52.95', '$52.96 - $77.65', '$77.66 - $114.05', '$114.06 - $201.75', 'No Revenue Data']
    },
    {
      id: 'house', label: 'House take', prop: 'House_Takes_ranges',
      preferred: ['0% - 12.5%', '12.6% - 25.0%', '25.1% - 33.5%', '33.6% - 41.2%', '41.3% - 68.7%', 'House Take Unknown']
    }
  ];

  var prefersReducedMotion = window.matchMedia &&
    window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  /* ------------------------------------------------------------------ *
   * DOM references
   * ------------------------------------------------------------------ */
  var slider = document.getElementById('date-slider');
  var dateOutput = document.getElementById('date-output');
  var filterContainer = document.getElementById('filter-groups');
  var resultCount = document.getElementById('result-count');
  var statusRegion = document.getElementById('status');
  var tableBody = document.querySelector('#shows-table tbody');
  var errorBox = document.getElementById('load-error');

  /* ------------------------------------------------------------------ *
   * Small helpers
   * ------------------------------------------------------------------ */
  function debounce(fn, wait) {
    var t;
    return function () {
      clearTimeout(t);
      t = setTimeout(fn, wait);
    };
  }

  // Re-setting the text after a tick makes screen readers repeat identical messages
  function announce(message) {
    statusRegion.textContent = '';
    setTimeout(function () { statusRegion.textContent = message; }, 50);
  }

  // Julian Day Number -> civil date (integer JDs are noon UTC of that day)
  function formatJD(jd) {
    var d = new Date((Number(jd) - 2440587.5) * 86400000);
    return d.toLocaleDateString('en-US', {
      timeZone: 'UTC', year: 'numeric', month: 'long', day: 'numeric'
    });
  }

  function text(value, fallback) {
    return (value === null || value === undefined || String(value).trim() === '') ?
      (fallback || 'Not recorded') : String(value);
  }

  function el(tag, props, children) {
    var node = document.createElement(tag);
    Object.keys(props || {}).forEach(function (k) {
      if (k === 'text') { node.textContent = props[k]; }
      else { node.setAttribute(k, props[k]); }
    });
    (children || []).forEach(function (c) { node.appendChild(c); });
    return node;
  }

  function showError(message) {
    errorBox.textContent = message;
    errorBox.hidden = false;
  }

  /* ------------------------------------------------------------------ *
   * Map
   * ------------------------------------------------------------------ */
  var blanktile = L.tileLayer('tiles/{z}/{x}/{y}.png', {
    minZoom: 5,
    maxZoom: 12,
    maxNativeZoom: 8, // tiles only exist to zoom 8; stretch them beyond that
    tms: false,
    attribution: 'Generated by TilesXYZ'
  });

  var map = L.map('map', {
    center: [37.2, -87],
    zoom: 5,
    minZoom: 5,
    maxZoom: 12,
    layers: [blanktile],
    zoomControl: false, // re-added below so we control its position
    keyboard: true,
    zoomAnimation: !prefersReducedMotion,
    fadeAnimation: !prefersReducedMotion,
    markerZoomAnimation: !prefersReducedMotion
  });

  // Keyboard- and screen-reader-operable +/- buttons
  L.control.zoom({
    position: 'topright',
    zoomInTitle: 'Zoom in',
    zoomOutTitle: 'Zoom out'
  }).addTo(map);

  // Keep panning inside the United States
  map.setMaxBounds(L.latLngBounds(L.latLng(51, -125), L.latLng(23, -69)));

  L.control.scale({ position: 'bottomright' }).addTo(map);

  var markerGroup = L.featureGroup().addTo(map);

  /* ------------------------------------------------------------------ *
   * State
   * ------------------------------------------------------------------ */
  var records = [];    // {layer, props, jd, dateLabel}
  var selected = {};   // groupId -> Set of selected values
  FILTER_GROUPS.forEach(function (g) { selected[g.id] = new Set(); });

  /* ------------------------------------------------------------------ *
   * Popups, focus handling
   * ------------------------------------------------------------------ */
  function buildPopupContent(props, dateLabel) {
    var rows = [
      ['Date', dateLabel],
      ['Venue', text(props.Venue)],
      ['Amount made', text(props.Amount_Made_D)],
      ['House take', text(props.House_Takes_P)],
      ['Notes', text(props.Notes, 'None')]
    ];
    var dl = el('dl', { 'class': 'popup-list' });
    rows.forEach(function (r) {
      dl.appendChild(el('dt', { text: r[0] }));
      dl.appendChild(el('dd', { text: r[1] }));
    });
    return el('div', { tabindex: '-1', 'class': 'popup-body' }, [
      el('h3', { 'class': 'popup-title', text: text(props.Town, 'Unknown town') + ', ' + text(props.State, '') }),
      dl
    ]);
  }

  var lastTrigger = null;

  map.on('popupopen', function (e) {
    var popupEl = e.popup.getElement();
    if (popupEl) {
      popupEl.setAttribute('role', 'dialog');
      popupEl.setAttribute('aria-label', 'Show details');
    }
    var active = document.activeElement;
    if (active && active !== document.body && !(popupEl && popupEl.contains(active))) {
      lastTrigger = active;
    }
    var body = popupEl && popupEl.querySelector('.popup-body');
    if (body) { body.focus(); } // moves screen reader users into the details
  });

  map.on('popupclose', function (e) {
    var popupEl = e.popup.getElement();
    var active = document.activeElement;
    var focusInPopup = popupEl && active && popupEl.contains(active);
    if ((focusInPopup || active === document.body) && lastTrigger && document.body.contains(lastTrigger)) {
      lastTrigger.focus();
    }
  });

  /* ------------------------------------------------------------------ *
   * Marker creation
   * ------------------------------------------------------------------ */
  function makeMarker(feature) {
    var coords = feature.geometry && feature.geometry.coordinates;
    if (!coords) { return null; }

    var props = feature.properties || {};
    var jd = Number(props.Julian_Date);
    var dateLabel = (props.Month && props.Day && props.Year) ?
      props.Month + ' ' + Number(props.Day) + ', ' + props.Year : formatJD(jd);
    var name = text(props.Town, 'Unknown town') + ', ' + text(props.State, '');
    var label = name + ', ' + dateLabel + '. Show details.';

    var layer = L.circleMarker(L.GeoJSON.coordsToLatLng(coords), L.extend({}, MARKER_STYLE, {
      className: 'brinton-marker'
    }));

    layer.bindPopup(buildPopupContent(props, dateLabel), { maxWidth: 320 });

    // Mouse hover (unchanged behavior)
    layer.on('mouseover', function () { layer.setStyle(ACTIVE_STYLE); });
    layer.on('mouseout', function () {
      if (document.activeElement !== layer.getElement()) { layer.setStyle(MARKER_STYLE); }
    });

    // Leaflet makes a fresh <path> every time the layer is added, so decorate on 'add'
    layer.on('add', function () {
      var path = layer.getElement();
      if (!path) { return; }
      path.setAttribute('tabindex', '0');
      path.setAttribute('role', 'button');
      path.setAttribute('aria-label', label);
      path.setAttribute('aria-haspopup', 'dialog');

      L.DomEvent.on(path, 'focus', function () { layer.setStyle(ACTIVE_STYLE); });
      L.DomEvent.on(path, 'blur', function () { layer.setStyle(MARKER_STYLE); });
      L.DomEvent.on(path, 'keydown', function (e) {
        if (e.key === 'Enter' || e.key === ' ' || e.key === 'Spacebar') {
          L.DomEvent.preventDefault(e);
          L.DomEvent.stopPropagation(e); // don't let the map treat it as a pan/zoom key
          layer.openPopup();
        }
      });
    });

    return { layer: layer, props: props, jd: jd, dateLabel: dateLabel, name: name };
  }

  /* ------------------------------------------------------------------ *
   * Filtering + rendering
   * ------------------------------------------------------------------ */
  function isVisible(rec) {
    if (rec.jd > Number(slider.value)) { return false; }
    return FILTER_GROUPS.every(function (g) {
      var set = selected[g.id];
      return set.size === 0 || set.has(String(rec.props[g.prop]));
    });
  }

  var visibleRecords = [];

  function applyFilters() {
    var current = Number(slider.value);
    dateOutput.textContent = formatJD(current);
    slider.setAttribute('aria-valuetext', formatJD(current));

    visibleRecords = [];
    records.forEach(function (rec) {
      var show = isVisible(rec);
      var onMap = markerGroup.hasLayer(rec.layer);
      if (show) {
        visibleRecords.push(rec);
        if (!onMap) { markerGroup.addLayer(rec.layer); }
      } else if (onMap) {
        markerGroup.removeLayer(rec.layer);
      }
    });

    resultCount.textContent = 'Showing ' + visibleRecords.length + ' of ' + records.length + ' shows.';
    renderTableSoon();
    announceSoon();
  }

  function renderTable() {
    tableBody.textContent = '';
    if (visibleRecords.length === 0) {
      var td = el('td', { colspan: '8', text: 'No shows match the current date and filters.' });
      tableBody.appendChild(el('tr', {}, [td]));
      return;
    }
    var frag = document.createDocumentFragment();
    visibleRecords.forEach(function (rec) {
      var p = rec.props;
      var btn = el('button', {
        type: 'button',
        text: 'Show on map',
        'aria-label': 'Show ' + rec.name + ', ' + rec.dateLabel + ', on map'
      });
      btn.addEventListener('click', function () {
        map.setView(rec.layer.getLatLng(), Math.max(map.getZoom(), 8), { animate: !prefersReducedMotion });
        document.getElementById('map').scrollIntoView({ block: 'center' });
        rec.layer.openPopup();
      });
      frag.appendChild(el('tr', {}, [
        el('th', { scope: 'row', text: rec.dateLabel }),
        el('td', { text: text(p.Town) }),
        el('td', { text: text(p.State) }),
        el('td', { text: text(p.Venue) }),
        el('td', { text: text(p.Amount_Made_D) }),
        el('td', { text: text(p.House_Takes_P) }),
        el('td', { text: text(p.Notes, '') }),
        el('td', {}, [btn])
      ]));
    });
    tableBody.appendChild(frag);
  }

  var renderTableSoon = debounce(renderTable, 200);
  var announceSoon = debounce(function () {
    announce(resultCount.textContent);
  }, 800);

  /* ------------------------------------------------------------------ *
   * Filter UI: disclosure buttons containing labelled checkboxes
   * ------------------------------------------------------------------ */
  function orderedValues(group, features) {
    var seen = new Set();
    features.forEach(function (f) {
      var v = f.properties && f.properties[group.prop];
      if (v !== null && v !== undefined && String(v).trim() !== '') { seen.add(String(v)); }
    });
    var preferred = (group.preferred || []).filter(function (v) { return seen.has(v); });
    var extras = Array.from(seen).filter(function (v) { return preferred.indexOf(v) === -1; });
    extras.sort(function (a, b) { return a.localeCompare(b, 'en', { numeric: true }); });
    return preferred.concat(extras);
  }

  function updateSelectedCount(group, countNode) {
    var n = selected[group.id].size;
    countNode.textContent = n ? '(' + n + ' selected)' : '';
  }

  var groupUi = {}; // id -> {countNode, searchInput, checkboxes}

  function buildFilterGroup(group, values) {
    var toggleId = 'filter-toggle-' + group.id;
    var panelId = 'filter-panel-' + group.id;

    var countNode = el('span', { 'class': 'selected-count' });
    var toggle = el('button', {
      type: 'button', id: toggleId, 'class': 'filter-toggle',
      'aria-expanded': 'false', 'aria-controls': panelId
    }, [
      el('span', {}, [el('span', { text: group.label }), countNode]),
      el('span', { 'class': 'chevron', 'aria-hidden': 'true', text: '▸' })
    ]);

    var panel = el('div', { id: panelId, 'class': 'filter-panel', hidden: '' });
    var fieldset = el('fieldset');
    fieldset.appendChild(el('legend', { 'class': 'sr-only', text: group.label }));

    var searchInput = null;
    if (group.searchable) {
      var searchId = 'filter-search-' + group.id;
      fieldset.appendChild(el('label', { 'class': 'filter-search-label', 'for': searchId, text: 'Search ' + group.label.toLowerCase() + ' list' }));
      searchInput = el('input', { type: 'search', id: searchId, autocomplete: 'off' });
      fieldset.appendChild(searchInput);
    }

    var options = el('div', { 'class': 'filter-options' });
    var checkboxes = values.map(function (value, i) {
      var id = 'filter-' + group.id + '-' + i;
      var cb = el('input', { type: 'checkbox', id: id, value: value });
      cb.addEventListener('change', function () {
        if (cb.checked) { selected[group.id].add(value); } else { selected[group.id].delete(value); }
        updateSelectedCount(group, countNode);
        applyFilters();
      });
      options.appendChild(el('label', { 'for': id }, [cb, el('span', { text: value })]));
      return cb;
    });
    fieldset.appendChild(options);
    panel.appendChild(fieldset);

    toggle.addEventListener('click', function () {
      var open = toggle.getAttribute('aria-expanded') === 'true';
      toggle.setAttribute('aria-expanded', String(!open));
      panel.hidden = open;
    });

    if (searchInput) {
      searchInput.addEventListener('input', function () {
        var q = searchInput.value.trim().toLowerCase();
        var shown = 0;
        checkboxes.forEach(function (cb) {
          var match = cb.value.toLowerCase().indexOf(q) !== -1;
          cb.parentNode.hidden = !match;
          if (match) { shown++; }
        });
        announce(shown + (shown === 1 ? ' option' : ' options') + ' in ' + group.label.toLowerCase() + ' list.');
      });
    }

    groupUi[group.id] = { countNode: countNode, searchInput: searchInput, checkboxes: checkboxes, group: group };

    return el('div', { 'class': 'filter-group' }, [el('h3', {}, [toggle]), panel]);
  }

  function clearFilters() {
    FILTER_GROUPS.forEach(function (g) {
      selected[g.id].clear();
      var ui = groupUi[g.id];
      if (!ui) { return; }
      ui.checkboxes.forEach(function (cb) { cb.checked = false; cb.parentNode.hidden = false; });
      if (ui.searchInput) { ui.searchInput.value = ''; }
      updateSelectedCount(g, ui.countNode);
    });
    applyFilters();
    announce('All filters cleared. ' + resultCount.textContent);
  }

  /* ------------------------------------------------------------------ *
   * Wire up controls that exist before the data loads
   * ------------------------------------------------------------------ */
  slider.addEventListener('input', applyFilters);
  slider.addEventListener('change', applyFilters);

  document.getElementById('show-all-dates').addEventListener('click', function () {
    slider.value = slider.max;
    applyFilters();
  });
  document.getElementById('clear-filters').addEventListener('click', clearFilters);

  dateOutput.textContent = formatJD(slider.value);
  slider.setAttribute('aria-valuetext', formatJD(slider.value));

  /* ------------------------------------------------------------------ *
   * Load data
   * ------------------------------------------------------------------ */
  fetch(DATA_URL)
    .then(function (r) {
      if (!r.ok) { throw new Error('HTTP ' + r.status); }
      return r.json();
    })
    .then(function (geojson) {
      var features = (geojson.features || []);

      var bounds = L.latLngBounds([]);
      features.forEach(function (f) {
        var rec = makeMarker(f);
        if (rec) {
          records.push(rec);
          bounds.extend(rec.layer.getLatLng());
        }
      });
      records.sort(function (a, b) { return a.jd - b.jd; });

      FILTER_GROUPS.forEach(function (g) {
        filterContainer.appendChild(buildFilterGroup(g, orderedValues(g, features)));
      });

      if (bounds.isValid()) { map.fitBounds(bounds); }

      applyFilters();
      renderTable(); // render immediately on first load
      announce('Map loaded. ' + resultCount.textContent);
    })
    .catch(function (err) {
      showError('The show data could not be loaded (' + err.message + '). ' +
        'If you opened this file directly from disk, serve the folder over http (for example with "python3 -m http.server") and try again.');
    });
})();
